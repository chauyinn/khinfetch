type WidenStrings<T> = {
  [K in keyof T]: T[K] extends (...args: infer Args) => string
    ? (...args: Args) => string
    : T[K] extends string
      ? string
      : T[K] extends object
        ? WidenStrings<T[K]>
        : never;
};

export type Messages = WidenStrings<typeof strings>;
